const STORE_MAP = new Map(STORES.map((store) => [store.id, store]));
const PRODUCT_MAP = new Map(PRODUCTS.map((product) => [product.id, product]));

export function getStore(id: string): Store | undefined {
  return STORE_MAP.get(id);
}

export function getProduct(id: string): Product | undefined {
  return PRODUCT_MAP.get(id);
}

export function nearbyStores(): Store[] {
  return [...STORES].sort((a, b) => a.distanceKm - b.distanceKm);
}

export function stockRank(stock: StockStatus): number {
  if (stock === "IN_STOCK") return 0;
  if (stock === "LOW_STOCK") return 1;
  return 2;
}

export function productsForStore(storeId: string): Product[] {
  return PRODUCTS.filter((product) => product.storeId === storeId).sort(
    (a, b) => stockRank(a.stock) - stockRank(b.stock),
  );
}

export function productsForCategory(categoryId: CategoryId): { product: Product; store: Store }[] {
  return PRODUCTS.filter((product) => product.categoryId === categoryId)
    .flatMap((product) => {
      const store = getStore(product.storeId);
      return store ? [{ product, store }] : [];
    })
    .sort(
      (a, b) =>
        stockRank(a.product.stock) - stockRank(b.product.stock) ||
        a.store.distanceKm - b.store.distanceKm,
    );
}
